"""Turn a run's summary.json into the PR body, a score card PNG and a static dashboard, all in the run folder."""

import html
import json
from dataclasses import dataclass
from pathlib import Path

from . import paths, specs as specs_mod

STATUS_ICON = {"fixed": "✅ fixed", "unfixed": "❌ unfixed", "survived": "🟢 survived", "skipped": "⏭ skipped",
               "unreachable": "⚠️ unreachable", "declined": "💡 suggested"}


@dataclass
class Report:
    pr_body: Path
    score_card: Path
    dashboard: Path
    score: int
    fixed: int
    total: int


def load_summary(app_dir: Path, run_id: str) -> dict:
    f = paths.run_dir(app_dir, run_id) / "summary.json"
    if not f.exists():
        raise FileNotFoundError(f"no summary for run {run_id}: {f}")
    return json.loads(f.read_text())


def score_of(outcomes: list[dict]) -> int:
    """Resilience score: share of attacks the app now survives (fixed or survived to begin with)."""
    if not outcomes:
        return 0
    ok = sum(1 for o in outcomes if o["status"] in ("fixed", "survived"))
    return round(100 * ok / len(outcomes))


def _fault(name: str) -> str:
    t = specs_mod.builtin_templates().get(name.split("_on_")[0])
    return t["fault_type"] if t else "custom"


def pr_body(summary: dict, package: str) -> str:
    outs = summary.get("outcomes", [])
    fixed = [o for o in outs if o["status"] == "fixed"]
    score = score_of(outs)
    lines = [
        f"## droid-monkey: {len(fixed)} lifecycle bug{'s' if len(fixed) != 1 else ''} fixed in `{package}`",
        "",
        f"droid-monkey attacked the app on an emulator with real-world faults, fixed what broke, and proved each fix "
        f"by replaying the identical attack and running a new regression test. Resilience score: **{score}/100** "
        f"({sum(1 for o in outs if o['status'] in ('fixed', 'survived'))} of {len(outs)} attacks now survived).",
        "",
        "| Attack | Fault | Before | After | Fix commit | Entire checkpoint | Regression test | Attempts |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for o in outs:
        after = {"fixed": "survives (replayed)", "survived": "survives", "unfixed": "still fails",
                 "skipped": "not attempted", "unreachable": "screen not reachable",
                 "declined": "fix suggested, not applied"}[o["status"]]
        tests = ", ".join(Path(t).stem for t in o.get("tests", [])) or "-"
        lines.append(
            f"| `{o['attack']}` | {_fault(o['attack'])} | {o['before']}: {str(o.get('before_detail', ''))[:70]} | "
            f"{STATUS_ICON[o['status']]}: {after} | {('`' + o['commit'][:8] + '`') if o.get('commit') else '-'} | "
            f"{('`' + o['checkpoint'] + '`') if o.get('checkpoint') else '-'} | {tests} | {o.get('attempts', 0)} |")
    for o in fixed:
        d = o.get("diagnosis") or {}
        lines += ["", f"### `{o['attack']}`: {d.get('summary', '')}", "",
                  f"**Root cause.** {d.get('root_cause', '')}", "", f"**Fix.** {d.get('fix_approach', '')}", "",
                  f"**Files.** {', '.join('`' + f + '`' for f in o.get('files', []))}", "",
                  f"**Proof.** The identical attack was replayed on the rebuilt app and survived; "
                  f"{', '.join('`' + Path(t).stem + '`' for t in o.get('tests', []))} passes. "
                  f"Fix written in a recorded Claude Code session (Entire checkpoint `{o.get('checkpoint') or 'n/a'}`)."
                  + (f" Took {o['attempts']} attempts: the retry resumed the same session with a revised diagnosis."
                     if o.get("attempts", 0) > 1 else "")]
    unfixed = [o for o in outs if o["status"] == "unfixed"]
    if unfixed:
        lines += ["", "### Not fixed", ""] + [f"- `{o['attack']}`: {o.get('reason', '')[:300]}" for o in unfixed]
    declined = [o for o in outs if o["status"] == "declined"]
    if declined:
        lines += ["", "### Suggested fixes (not applied: declined at review)"]
        for o in declined:
            d = o.get("diagnosis") or {}
            lines += ["", f"**`{o['attack']}`: {d.get('summary', '')}**", "", f"- Root cause: {d.get('root_cause', '')}",
                      f"- Suggested fix: {d.get('fix_approach', '')}",
                      f"- Files: {', '.join('`' + f + '`' for f in d.get('files_to_change', []))}"]
            lines += [f"- Evidence: {e}" for e in (o.get("suggestion") or {}).get("evidence", [])[:6]]
    lines += ["", f"Run `{summary['run_id']}` on branch `{summary.get('branch')}`. Evidence (screenshots, UI dumps, "
              "crash logs, verdicts) is in `.droid-monkey/runs/` of the run. Generated by "
              "[droid-monkey](https://github.com/shubhasai/droid-monkey)."]
    return "\n".join(lines) + "\n"


def score_card(summary: dict, package: str, out: Path) -> None:
    from PIL import Image, ImageDraw, ImageFont

    outs = summary.get("outcomes", [])
    score = score_of(outs)
    w, h = 1200, 260 + 70 * len(outs)
    img = Image.new("RGB", (w, h), (18, 22, 34))
    draw = ImageDraw.Draw(img)

    def font(size: int):
        for name in ("/System/Library/Fonts/SFNS.ttf", "/System/Library/Fonts/Helvetica.ttc", "DejaVuSans.ttf"):
            try:
                return ImageFont.truetype(name, size)
            except OSError:
                continue
        return ImageFont.load_default()

    draw.text((60, 50), "droid-monkey resilience", font=font(44), fill=(231, 234, 243))
    draw.text((60, 110), package, font=font(28), fill=(154, 163, 184))
    color = (95, 211, 154) if score >= 75 else (240, 192, 96) if score >= 50 else (255, 138, 128)
    big, small = font(120), font(36)
    sw = draw.textbbox((0, 0), str(score), font=big)[2]
    tw = draw.textbbox((0, 0), "/100", font=small)[2]
    x = w - 60 - tw - 12 - sw
    draw.text((x, 40), str(score), font=big, fill=color)
    draw.text((x + sw + 12, 128), "/100", font=small, fill=(154, 163, 184))
    palette = {"fixed": (95, 211, 154), "survived": (141, 156, 255), "unfixed": (255, 138, 128),
               "skipped": (154, 163, 184), "unreachable": (240, 192, 96), "declined": (240, 192, 96)}
    y = 220
    for o in outs:
        draw.rounded_rectangle((60, y, w - 60, y + 54), radius=10, fill=(30, 36, 54))
        draw.text((84, y + 12), o["attack"], font=font(28), fill=(231, 234, 243))
        label = {"fixed": f"fixed  {o.get('before')} → survives", "survived": "survived",
                 "unfixed": f"unfixed ({o.get('before')})", "skipped": "skipped",
                 "unreachable": "screen unreachable", "declined": f"fix suggested ({o.get('before')})"}[o["status"]]
        draw.text((520, y + 12), label, font=font(28), fill=palette[o["status"]])
        if o.get("commit"):
            draw.text((w - 240, y + 12), o["commit"][:8], font=font(26), fill=(154, 163, 184))
        y += 70
    img.save(out)


PROBLEMS = ("crashed", "anr", "lost_state", "no_feedback", "leaked", "froze", "slow_start")


def receipt_data(summary: dict) -> dict:
    outs = summary.get("outcomes", [])
    m = [o.get("metrics") or {} for o in outs]
    found: dict[str, int] = {}
    for o in outs:
        if o.get("before") in PROBLEMS:
            found[o["before"]] = found.get(o["before"], 0) + 1
    by = lambda s: sum(1 for o in outs if o["status"] == s)
    reasoning = summary.get("reasoning") or {}
    diag_tokens = sum(x.get("diag_tokens", 0) for x in m)
    diag_cost = sum(x.get("diag_cost_usd", 0.0) for x in m)
    agent = summary.get("coder_agent", "claude")
    return {
        "attacks": len(outs), "screens": len({x["screen"] for x in m if x.get("screen")}),
        "found": found, "fixed": by("fixed"), "first_try": sum(1 for o in outs if o["status"] == "fixed"
                                                                and o.get("attempts", 0) == 1),
        "declined": by("declined"), "unfixed": by("unfixed"), "survived": by("survived"),
        "unreachable": by("unreachable"), "minutes": round((summary.get("seconds") or sum(x.get("seconds", 0) for x in m)) / 60, 1),
        "reasoning_model": reasoning.get("model", summary.get("diagnoser_model", "?")),
        "reasoning_tokens": (reasoning.get("input_tokens") or 0) + (reasoning.get("output_tokens") or 0),
        "reasoning_cost": reasoning.get("cost_usd") or 0.0, "diag_tokens": diag_tokens, "diag_cost": diag_cost,
        "coder_agent": agent, "coder_model": summary.get("coder_model", "?"),
        "coder_sessions": sum(x.get("attempts", 0) for x in m), "coder_tokens": sum(x.get("coder_tokens", 0) for x in m),
        "coder_cost": sum(x.get("coder_cost_usd", 0.0) for x in m),
        "coder_billing": "API" if agent == "api" else ("Codex plan" if agent == "codex" else "Claude plan, API-equivalent"),
    }


def receipt(summary: dict, package: str) -> str:
    """What the run found and fixed, and what it cost, per step."""
    r = receipt_data(summary)
    found = ", ".join(f"{n} {k}" for k, n in sorted(r["found"].items(), key=lambda kv: -kv[1])) or "nothing"
    api = r["reasoning_cost"] + r["diag_cost"] + (r["coder_cost"] if r["coder_agent"] == "api" else 0.0)
    plan = 0.0 if r["coder_agent"] == "api" else r["coder_cost"]
    rows = [
        ("attacks", f"{r['attacks']}" + (f" on {r['screens']} screen{'s' if r['screens'] != 1 else ''}" if r["screens"] else "")),
        ("found", f"{sum(r['found'].values())} problems: {found}"),
        ("fixed", f"{r['fixed']} ({r['first_try']} on the first try) · declined {r['declined']} · unfixed {r['unfixed']}"),
        ("survived", f"{r['survived']}" + (f" · unreachable {r['unreachable']}" if r["unreachable"] else "")),
        ("time", f"{r['minutes']} min"),
        ("plan + decide", f"{r['reasoning_model']}, {r['reasoning_tokens']:,} tokens, ${r['reasoning_cost']:.4f} (API)"),
        ("diagnosis", f"{r['reasoning_model']}, {r['diag_tokens']:,} tokens, ${r['diag_cost']:.4f} (API)"),
        ("fixes", f"{r['coder_agent']} / {r['coder_model']}, {r['coder_sessions']} sessions, {r['coder_tokens']:,} tokens, "
                  f"${r['coder_cost']:.2f} ({r['coder_billing']})"),
        ("total", f"${api:.4f} API" + (f" + ${plan:.2f} {r['coder_billing']}" if plan else "")),
    ]
    width = max(len(k) for k, _ in rows)
    lines = [f"droid-monkey receipt · run {summary.get('run_id')} · {package}", ""]
    lines += [f"{k:<{width}}  {v}" for k, v in rows]
    return "\n".join(lines) + "\n"


def _verdict(ev: Path) -> dict:
    try:
        return json.loads((ev / "verdict.json").read_text())
    except (OSError, ValueError):
        return {}


def _latest_replay(ev: Path) -> Path | None:
    replays = sorted((p for p in ev.glob("replay-*") if p.is_dir()), key=lambda p: p.name)
    return replays[-1] if replays else None


def _fix_diff(app_dir: Path | None, commit: str | None) -> str:
    """The fix commit's source diff, coloured."""
    if not app_dir or not commit:
        return ""
    import subprocess
    out = subprocess.run(["git", "show", "--format=", "--no-color", commit], cwd=app_dir, capture_output=True,
                         text=True, stdin=subprocess.DEVNULL).stdout
    lines = []
    for ln in out.splitlines()[:400]:
        cls = ("add" if ln.startswith("+") and not ln.startswith("+++") else
               "del" if ln.startswith("-") and not ln.startswith("---") else
               "hunk" if ln.startswith("@@") else "file" if ln.startswith(("diff ", "+++", "---")) else "")
        lines.append(f'<span class="{cls}">{html.escape(ln)}</span>' if cls else html.escape(ln))
    return "<pre class='diff'>" + "\n".join(lines) + "</pre>" if lines else ""


def _media(rel: str, ev: Path, caption: str) -> str:
    """The attack's screen recording (or its last screenshot), captioned."""
    if (ev / "recording.mp4").exists():
        return (f'<figure class="video"><video controls muted playsinline preload="metadata" src="{rel}/recording.mp4">'
                f'</video><figcaption>{html.escape(caption)}</figcaption></figure>')
    if (ev / "after.png").exists():
        return f'<figure><img src="{rel}/after.png" alt=""><figcaption>{html.escape(caption)}</figcaption></figure>'
    return ""


def _visuals(o: dict, ev: Path, rel: str, app_dir: Path | None) -> str:
    """The evidence a reader needs for this kind of failure, as pictures where a picture says it better."""
    from . import charts
    from .runner import SpecRunner
    v = _verdict(ev)
    m = v.get("metrics") or o.get("metrics") or {}
    parts = []

    # What happened, on screen: the attack, and the same attack replayed after the fix.
    replay = _latest_replay(ev)
    videos = [_media(rel, ev, f"the attack: {o['before']}")]
    if replay is not None and o["status"] == "fixed":
        videos.append(_media(f"{rel}/{replay.name}", replay, "the identical attack, replayed after the fix: survived"))
    captions = {"before": "the start screen", "fault": "the moment the fault hit", "after": "after the fault"}
    shots = "".join(f'<figure><img src="{rel}/{n}.png" alt="{captions[n]}"><figcaption>{captions[n]}</figcaption></figure>'
                    for n in ("before", "fault", "after") if (ev / f"{n}.png").exists())
    if any(videos):
        parts.append(f'<h3>On screen</h3><div class="media">{"".join(videos)}</div>')
    if shots:
        parts.append(f'<div class="shots">{shots}</div>')

    lost = v.get("lost_fields") or {}
    if lost:
        rows = "".join(f"<tr><td><code>{html.escape(k)}</code></td><td>{html.escape(str(b))}</td>"
                       f"<td class='bad'>{html.escape(str(a)) or '<i>empty</i>'}</td></tr>" for k, (b, a) in lost.items())
        parts.append(f"<h3>Lost input</h3><table><tr><th>field</th><th>before the fault</th><th>after</th></tr>{rows}</table>")

    trace = m.get("trace") or {}
    timeline = charts.main_thread(trace.get("main_timeline") or {}, trace.get("long_main_slices") or [])
    if timeline:
        parts.append(f"<h3>Main thread (Perfetto)</h3>{timeline}")
    frames = charts.frame_times((m.get("frames") or {}).get("histogram") or [])
    if frames:
        parts.append(f"<h3>Frame times</h3>{frames}")
    if m.get("startup"):
        parts.append(f"<h3>Launch times</h3>{charts.launches(m['startup'], SpecRunner.START_LIMITS_MS)}")
    mem = charts.memory(m.get("memory_before") or {}, m.get("memory_after") or {})
    if mem:
        parts.append(f"<h3>Memory after a forced GC</h3>{mem}")
    rss = charts.rss(trace.get("rss_series") or [])
    if rss:
        parts.append(f"<details><summary>resident memory over time</summary>{rss}</details>")

    diff = _fix_diff(app_dir, o.get("commit"))
    if diff:
        parts.append(f"<details open><summary>the fix ({html.escape(o['commit'][:8])})</summary>{diff}</details>")
    return "".join(parts)



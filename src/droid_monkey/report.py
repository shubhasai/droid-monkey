"""Turn a run's summary.json into the PR body, a score card PNG and a static dashboard, all in the run folder."""

import html
import json
from dataclasses import dataclass
from pathlib import Path

from . import paths, specs as specs_mod

STATUS_ICON = {"fixed": "✅ fixed", "unfixed": "❌ unfixed", "survived": "🟢 survived", "skipped": "⏭ skipped"}


@dataclass
class Report:
    pr_body: Path
    score_card: Path
    dashboard: Path
    score: int
    fixed: int
    total: int


def load_summary(app_dir: Path, run_id: str) -> dict:
    f = paths.run_dir(app_dir, run_id) / "summary.json"
    if not f.exists():
        raise FileNotFoundError(f"no summary for run {run_id}: {f}")
    return json.loads(f.read_text())


def score_of(outcomes: list[dict]) -> int:
    """Resilience score: share of attacks the app now survives (fixed or survived to begin with)."""
    if not outcomes:
        return 0
    ok = sum(1 for o in outcomes if o["status"] in ("fixed", "survived"))
    return round(100 * ok / len(outcomes))


def _fault(name: str) -> str:
    t = specs_mod.builtin_templates().get(name)
    return t["fault_type"] if t else "custom"


def pr_body(summary: dict, package: str) -> str:
    outs = summary.get("outcomes", [])
    fixed = [o for o in outs if o["status"] == "fixed"]
    score = score_of(outs)
    lines = [
        f"## droid-monkey: {len(fixed)} lifecycle bug{'s' if len(fixed) != 1 else ''} fixed in `{package}`",
        "",
        f"droid-monkey attacked the app on an emulator with real-world faults, fixed what broke, and proved each fix "
        f"by replaying the identical attack and running a new regression test. Resilience score: **{score}/100** "
        f"({sum(1 for o in outs if o['status'] in ('fixed', 'survived'))} of {len(outs)} attacks now survived).",
        "",
        "| Attack | Fault | Before | After | Fix commit | Entire checkpoint | Regression test | Attempts |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for o in outs:
        after = {"fixed": "survives (replayed)", "survived": "survives", "unfixed": "still fails",
                 "skipped": "not attempted"}[o["status"]]
        tests = ", ".join(Path(t).stem for t in o.get("tests", [])) or "-"
        lines.append(
            f"| `{o['attack']}` | {_fault(o['attack'])} | {o['before']}: {str(o.get('before_detail', ''))[:70]} | "
            f"{STATUS_ICON[o['status']]}: {after} | {('`' + o['commit'][:8] + '`') if o.get('commit') else '-'} | "
            f"{('`' + o['checkpoint'] + '`') if o.get('checkpoint') else '-'} | {tests} | {o.get('attempts', 0)} |")
    for o in fixed:
        d = o.get("diagnosis") or {}
        lines += ["", f"### `{o['attack']}`: {d.get('summary', '')}", "",
                  f"**Root cause.** {d.get('root_cause', '')}", "", f"**Fix.** {d.get('fix_approach', '')}", "",
                  f"**Files.** {', '.join('`' + f + '`' for f in o.get('files', []))}", "",
                  f"**Proof.** The identical attack was replayed on the rebuilt app and survived; "
                  f"{', '.join('`' + Path(t).stem + '`' for t in o.get('tests', []))} passes. "
                  f"Fix written in a recorded Claude Code session (Entire checkpoint `{o.get('checkpoint') or 'n/a'}`)."
                  + (f" Took {o['attempts']} attempts: the retry resumed the same session with a revised diagnosis."
                     if o.get("attempts", 0) > 1 else "")]
    unfixed = [o for o in outs if o["status"] == "unfixed"]
    if unfixed:
        lines += ["", "### Not fixed", ""] + [f"- `{o['attack']}`: {o.get('reason', '')[:300]}" for o in unfixed]
    lines += ["", f"Run `{summary['run_id']}` on branch `{summary.get('branch')}`. Evidence (screenshots, UI dumps, "
              "crash logs, verdicts) is in `.droid-monkey/runs/` of the run. Generated by "
              "[droid-monkey](https://github.com/shubhasai/droid-monkey)."]
    return "\n".join(lines) + "\n"


def score_card(summary: dict, package: str, out: Path) -> None:
    from PIL import Image, ImageDraw, ImageFont

    outs = summary.get("outcomes", [])
    score = score_of(outs)
    w, h = 1200, 260 + 70 * len(outs)
    img = Image.new("RGB", (w, h), (18, 22, 34))
    draw = ImageDraw.Draw(img)

    def font(size: int):
        for name in ("/System/Library/Fonts/SFNS.ttf", "/System/Library/Fonts/Helvetica.ttc", "DejaVuSans.ttf"):
            try:
                return ImageFont.truetype(name, size)
            except OSError:
                continue
        return ImageFont.load_default()

    draw.text((60, 50), "droid-monkey resilience", font=font(44), fill=(231, 234, 243))
    draw.text((60, 110), package, font=font(28), fill=(154, 163, 184))
    color = (95, 211, 154) if score >= 75 else (240, 192, 96) if score >= 50 else (255, 138, 128)
    big, small = font(120), font(36)
    sw = draw.textbbox((0, 0), str(score), font=big)[2]
    tw = draw.textbbox((0, 0), "/100", font=small)[2]
    x = w - 60 - tw - 12 - sw
    draw.text((x, 40), str(score), font=big, fill=color)
    draw.text((x + sw + 12, 128), "/100", font=small, fill=(154, 163, 184))
    palette = {"fixed": (95, 211, 154), "survived": (141, 156, 255), "unfixed": (255, 138, 128), "skipped": (154, 163, 184)}
    y = 220
    for o in outs:
        draw.rounded_rectangle((60, y, w - 60, y + 54), radius=10, fill=(30, 36, 54))
        draw.text((84, y + 12), o["attack"], font=font(28), fill=(231, 234, 243))
        label = {"fixed": f"fixed  {o.get('before')} → survives", "survived": "survived",
                 "unfixed": f"unfixed ({o.get('before')})", "skipped": "skipped"}[o["status"]]
        draw.text((520, y + 12), label, font=font(28), fill=palette[o["status"]])
        if o.get("commit"):
            draw.text((w - 240, y + 12), o["commit"][:8], font=font(26), fill=(154, 163, 184))
        y += 70
    img.save(out)


def dashboard(summary: dict, package: str, run_dir: Path, out: Path) -> None:
    outs = summary.get("outcomes", [])
    rows = []
    for o in outs:
        d = o.get("diagnosis") or {}
        ev = run_dir / o["attack"]
        shots = "".join(f'<figure><img src="{o["attack"]}/{n}.png" alt="{n}"><figcaption>{n}</figcaption></figure>'
                        for n in ("before", "after") if (ev / f"{n}.png").exists())
        rows.append(f"""<section class="card {o['status']}">
  <header><h2>{html.escape(o['attack'])}</h2><span class="pill">{html.escape(o['status'])}</span></header>
  <p class="meta">was <b>{html.escape(o['before'])}</b>: {html.escape(str(o.get('before_detail', '')))}</p>
  {f"<p><b>Root cause.</b> {html.escape(d.get('root_cause', ''))}</p><p><b>Fix.</b> {html.escape(d.get('fix_approach', ''))}</p>" if d else ""}
  {f"<p class='meta'>commit <code>{o['commit'][:8]}</code> · Entire checkpoint <code>{o.get('checkpoint') or '-'}</code> · tests {', '.join(Path(t).stem for t in o.get('tests', []))} · attempts {o.get('attempts', 0)}</p>" if o.get('commit') else ""}
  <div class="shots">{shots}</div>
</section>""")
    out.write_text(f"""<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width">
<title>droid-monkey run {html.escape(summary['run_id'])}</title>
<style>
:root{{--bg:#f5f6f8;--fg:#141a2b;--muted:#5a6275;--card:#fff;--line:#dde1e9;--ok:#1d7a4c;--bad:#b8322a;--acc:#2f45c9}}
@media (prefers-color-scheme:dark){{:root{{--bg:#0f1320;--fg:#e7eaf3;--muted:#9aa3b8;--card:#171c2c;--line:#2a3146;--ok:#5fd39a;--bad:#ff8a80;--acc:#8d9cff}}}}
body{{background:var(--bg);color:var(--fg);font:15px/1.5 -apple-system,system-ui,sans-serif;margin:0;padding:32px 16px}}
main{{max-width:960px;margin:0 auto;display:grid;gap:16px}} h1{{margin:0}} .muted,.meta{{color:var(--muted)}}
.score{{font-size:56px;font-weight:800;color:var(--acc)}} .card{{background:var(--card);border:1px solid var(--line);border-radius:10px;padding:16px}}
.card header{{display:flex;justify-content:space-between;align-items:center}} .card h2{{margin:0;font-size:18px}}
.pill{{font:600 12px ui-monospace,monospace;padding:4px 8px;border-radius:6px;border:1px solid var(--line)}}
.fixed .pill{{color:var(--ok)}} .unfixed .pill{{color:var(--bad)}} .shots{{display:flex;gap:12px;flex-wrap:wrap}}
figure{{margin:0}} img{{width:180px;border-radius:8px;border:1px solid var(--line)}} figcaption{{font-size:12px;color:var(--muted)}}
</style></head><body><main>
<h1>droid-monkey · {html.escape(package)}</h1>
<p class="muted">run {html.escape(summary['run_id'])} · branch {html.escape(str(summary.get('branch')))}</p>
<div class="score">{score_of(outs)}<span class="muted" style="font-size:20px">/100 resilience</span></div>
{''.join(rows)}
</main></body></html>""")


def build(app_dir: Path, package: str, run_id: str) -> Report:
    summary = load_summary(app_dir, run_id)
    run_dir = paths.run_dir(app_dir, run_id)
    body = run_dir / "pr-body.md"
    body.write_text(pr_body(summary, package))
    card = run_dir / "score-card.png"
    score_card(summary, package, card)
    dash = run_dir / "dashboard.html"
    dashboard(summary, package, run_dir, dash)
    outs = summary.get("outcomes", [])
    return Report(body, card, dash, score_of(outs), sum(1 for o in outs if o["status"] == "fixed"), len(outs))
